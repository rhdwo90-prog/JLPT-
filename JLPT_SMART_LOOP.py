def app_data_dir():
    base = os.getenv("APPDATA") or str(Path.home())
    p = Path(base) / "JLPT_SMART_LOOP"
    p.mkdir(parents=True, exist_ok=True)
    return p


class SpeechEngine:
    def __init__(self):
        self.voice = "ja-JP-NanamiNeural"
        self.rate = "+3%"
        self.pitch = "+4Hz"
        self.cache = app_data_dir() / "tts_cache"
        self.cache.mkdir(parents=True, exist_ok=True)
        self.alias = "jlpt_smart_tts"
        self._lock = threading.Lock()

    def _cache_path(self, text):
        key = hashlib.sha1((self.voice + text).encode("utf-8")).hexdigest()
        return self.cache / f"{key}.mp3"

    async def _make(self, text, path):
        import edge_tts
        await edge_tts.Communicate(text=text, voice=self.voice, rate=self.rate, pitch=self.pitch).save(str(path))

    def _mci(self, cmd):
        import ctypes
        buf = ctypes.create_unicode_buffer(512)
        ctypes.windll.winmm.mciSendStringW(cmd, buf, 512, None)
        return buf.value

    def stop(self):
        if not sys.platform.startswith("win"):
            return
        with self._lock:
            try:
                self._mci(f"stop {self.alias}")
                self._mci(f"close {self.alias}")
            except Exception:
                pass

    def speak(self, text):
        text = (text or "").strip()
        if not text:
            return

        def worker():
            try:
                path = self._cache_path(text)
                if not path.exists() or path.stat().st_size < 800:
                    asyncio.run(self._make(text, path))
                if sys.platform.startswith("win"):
                    self.stop()
                    safe = str(path).replace('"', '')
                    with self._lock:
                        self._mci(f'open "{safe}" type mpegvideo alias {self.alias}')
                        self._mci(f'play {self.alias}')
                else:
                    opener = "open" if sys.platform == "darwin" else "xdg-open"
                    subprocess.Popen([opener, str(path)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            except ModuleNotFoundError:
                # 음성은 부가기능이라 학습 흐름을 막지 않습니다.
                pass
            except Exception:
                pass

