    @staticmethod
    def mastery_text(p):
        m = int(p.get("mastery", 0))
        return ["신규", "흐림", "낯익음", "익숙함", "강함", "장기기억"][max(0, min(5, m))]

    def refresh_dashboard(self):
        pool = self.words if self.level_filter == "전체" else [w for w in self.words if w.get("level") == self.level_filter]
        now = time.time()
        new = sum(1 for w in pool if w["progress"]["status"] == "new")
        due = sum(1 for w in pool if w["progress"]["status"] != "new" and float(w["progress"].get("due_at", 0)) <= now)
        mastered = sum(1 for w in pool if int(w["progress"].get("mastery", 0)) >= 4)
        weak = sum(1 for w in pool if w["progress"]["status"] != "new" and int(w["progress"].get("mastery", 0)) <= 2)
        self.today_label.config(text=f"현재 범위  {len(pool)}개\n\n새 단어  {new}\n오늘 복습  {due}\n약한 단어  {weak}\n기억 강함  {mastered}")
        acc = (self.session_correct / self.session_questions * 100) if self.session_questions else 0
        self.session_label.config(text=f"이번 세션 · 신규 {self.session_new}/{self.new_target} · 문제 {self.session_questions} · 정답률 {acc:.0f}%")

