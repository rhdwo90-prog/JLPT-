        win.configure(bg=COLORS["bg"])
        cols = ("id", "level", "word", "reading", "meaning", "memory", "seen", "wrong", "next")
        tree = ttk.Treeview(win, columns=cols, show="headings")
        heads = {"id":"ID","level":"급수","word":"단어","reading":"읽기","meaning":"뜻","memory":"기억","seen":"노출","wrong":"오답","next":"다음 복습"}
        widths = {"id":55,"level":55,"word":115,"reading":130,"meaning":190,"memory":90,"seen":60,"wrong":60,"next":150}
