    # ---------------- data / scheduling ----------------
    def allowed_words(self):
        level = self.level_filter
        pool = self.words if level == "전체" else [w for w in self.words if w.get("level") == level]
        if self.focus_weak:
            weak = [w for w in pool if w["progress"]["status"] != "new" and (
                w["progress"]["mastery"] <= 2 or w["progress"]["lapses"] > 0
            )]
            if weak:
                pool = weak
        return pool

    def queue_word(self, wid, after_steps):
        due = self.step + max(1, int(after_steps))
        for item in self.immediate_queue:
            if item["id"] == wid:
                item["due"] = min(item["due"], due)
                return
        self.immediate_queue.append({"id": wid, "due": due})

    def pop_immediate_due(self, allowed_ids):
        due = [x for x in self.immediate_queue if x["due"] <= self.step and x["id"] in allowed_ids]
        if not due:
            return None
        due.sort(key=lambda x: x["due"])
        item = due[0]
        self.immediate_queue.remove(item)
        return self.word_map.get(item["id"])

    def pick_new(self, pool):
        candidates = [w for w in pool if w["progress"]["status"] == "new" and w["id"] not in self.last_ids[-8:]]
        if not candidates:
            candidates = [w for w in pool if w["progress"]["status"] == "new"]
        return random.choice(candidates) if candidates else None

    def pick_review(self, pool):
        now = time.time()
        reviewed = [w for w in pool if w["progress"]["status"] != "new" and w["id"] != self.current_id]
        if not reviewed:
            return None
        due = [w for w in reviewed if float(w["progress"].get("due_at", 0)) <= now]
        candidates = due or reviewed

        def weight(w):
            p = w["progress"]
            overdue_days = max(0.0, (now - float(p.get("due_at", 0))) / 86400.0)
            weak = (5 - int(p.get("mastery", 0))) * 2.0
            lapses = int(p.get("lapses", 0)) * 1.5
            recent_penalty = 0.15 if w["id"] in self.last_ids[-5:] else 1.0
            return max(0.2, (2.0 + weak + min(8.0, overdue_days) + lapses) * recent_penalty)

        weights = [weight(w) for w in candidates]
        return random.choices(candidates, weights=weights, k=1)[0]

    def select_next_word(self):
        pool = self.allowed_words()
        if not pool:
            return None, None
        allowed_ids = {w["id"] for w in pool}

        immediate = self.pop_immediate_due(allowed_ids)
        if immediate:
            return immediate, "quiz"

        # 새 단어를 몰아서 보여주지 않고, 최소 2문제 간격으로 천천히 투입합니다.
        can_intro = self.session_new < self.new_target and self.questions_since_intro >= 2 and not self.focus_weak
        if self.session_questions == 0 and self.session_new == 0 and not self.focus_weak:
            can_intro = True
        if can_intro:
            new_word = self.pick_new(pool)
            if new_word:
                return new_word, "intro"

        review = self.pick_review(pool)
        if review:
            return review, "quiz"

        new_word = self.pick_new(pool)
        if new_word and not self.focus_weak:
            return new_word, "intro"
        return None, None

    def start_next(self):
        self.step += 1
        self.answer_locked = False
        self.question = None
        self.current_selected_index = None
        self.current_correct = None
        self.current_revealed = False
        w, stage = self.select_next_word()
        if not w:
            self.current_id = None
            self.show_empty_state()
            return
        self.current_id = w["id"]
        self.current_stage = stage
        self.last_ids.append(w["id"])
        self.last_ids = self.last_ids[-16:]
        w["progress"]["seen"] += 1
        w["progress"]["last_seen"] = time.time()
        if stage == "intro":
            self.show_intro(w)
        else:
            self.show_quiz(w)
        self.refresh_dashboard()
        # 새 카드가 화면에 뜨는 즉시 저장하여 이 화면 그대로 복원할 수 있게 합니다.
        self.save_state()

    def finish_intro(self):
        if not self.current_id or self.current_stage != "intro":
            return
        w = self.word_map[self.current_id]
        p = w["progress"]
        p["status"] = "learning"
        p["mastery"] = max(0, int(p.get("mastery", 0)))
        p["due_at"] = time.time()
        self.session_new += 1
        self.questions_since_intro = 0
        # 2~4개의 다른 카드 뒤에 첫 회상 문제를 만납니다.
        self.queue_word(w["id"], random.randint(2, 4))
        self.save_state()
        self.start_next()

    def build_question(self, w):
        modes = ["word_mean", "word_read", "mean_word"]
        # 막 배우기 시작한 단어는 우선 한자→뜻 비중을 높여 진입장벽을 낮춥니다.
        mastery = int(w["progress"].get("mastery", 0))
        if mastery <= 1:
            mode = random.choices(modes, weights=[5, 3, 2], k=1)[0]
        else:
            mode = random.choice(modes)

        if mode == "word_mean":
            prompt, correct, field = w["word"], w["meaning"], "meaning"
            hint = "이 단어의 뜻은?"
        elif mode == "word_read":
            prompt, correct, field = w["word"], w["reading"], "reading"
            hint = "이 단어는 어떻게 읽을까?"
        else:
            prompt, correct, field = w["meaning"], w["word"], "word"
            hint = "이 뜻에 맞는 일본어는?"

        same_level = [x for x in self.words if x["id"] != w["id"] and x.get("level") == w.get("level")]
        random.shuffle(same_level)
        distractors = []
        used = {str(correct).strip()}
        for x in same_level:
            val = str(x.get(field, "")).strip()
            if not val or val in used:
                continue
            used.add(val)
            distractors.append(val)
            if len(distractors) == 3:
                break
        while len(distractors) < 3:
            distractors.append("—")
        options = distractors + [correct]
        random.shuffle(options)
        return {"mode": mode, "hint": hint, "prompt": prompt, "correct": correct, "options": options}

    def choose_option(self, index):
        if self.current_stage != "quiz" or self.answer_locked or not self.question:
            return
        if not (0 <= index < len(self.question["options"])):
            return
        self.answer_locked = True
        chosen = self.question["options"][index]
        correct = chosen == self.question["correct"]
        self.finish_question(correct, index)

    def reveal_without_choice(self):
        if self.current_stage != "quiz" or self.answer_locked or not self.question:
            return
        self.answer_locked = True
        self.finish_question(False, None, revealed=True)

    def finish_question(self, correct, selected_index=None, revealed=False):
        w = self.word_map[self.current_id]
        p = w["progress"]
        self.current_selected_index = selected_index
        self.current_correct = bool(correct)
        self.current_revealed = bool(revealed)
        self.session_questions += 1
        self.questions_since_intro += 1
        if correct:
            self.session_correct += 1
            p["correct"] += 1
            self.feedback.config(text="✓ 맞았어요. 기억 강도를 선택하세요.", fg=COLORS["green"])
        else:
            self.session_wrong += 1
            p["wrong"] += 1
            p["lapses"] += 1
            self.feedback.config(text="정답을 확인하고 다시 연결해두세요.", fg=COLORS["red"])

        correct_value = self.question["correct"]
        for i, btn in enumerate(self.option_buttons):
            btn.configure(state="disabled")
            value = self.question["options"][i]
            if value == correct_value:
                btn.configure(bg=COLORS["green_soft"], fg=COLORS["green"])
            elif i == selected_index:
                btn.configure(bg=COLORS["red_soft"], fg=COLORS["red"])

        self.subprompt.config(text=f"{w.get('reading','')}   ·   {w.get('meaning','')}")
        example = w.get("example_jp", "")
        kr = w.get("example_kr", "")
        self.reveal.config(text=f"{example}\n{kr}" if example or kr else "")
        if example or w.get("word"):
            self.quiz_speak_frame.pack(side="bottom", pady=(1, 3), before=self.grade_frame)
        self.set_grades_enabled(True)
        self.memory_label.config(text="추천: " + ("3 앎 / 4 쉬움" if correct else "1 모름 / 2 헷갈림"))
        # 기억 강도 선택 전 화면도 즉시 체크포인트
        self.save_state()

    def grade(self, quality):
        if self.current_stage != "quiz" or not self.answer_locked or not self.current_id:
            return
        w = self.word_map[self.current_id]
        p = w["progress"]
        now = time.time()
        old_mastery = int(p.get("mastery", 0))
        old_interval = float(p.get("interval", 0) or 0)

        if quality == 1:  # 모름
            p["mastery"] = max(0, old_mastery - 1)
            p["streak"] = 0
            p["status"] = "learning"
            p["interval"] = 0
            p["due_at"] = now
            self.queue_word(w["id"], 2)
        elif quality == 2:  # 헷갈림
            p["mastery"] = max(1, old_mastery)
            p["streak"] = max(0, int(p.get("streak", 0)))
            p["status"] = "learning"
            p["interval"] = 0
            p["due_at"] = now
            self.queue_word(w["id"], 5)
        elif quality == 3:  # 앎
            p["mastery"] = min(5, old_mastery + 1)
            p["streak"] = int(p.get("streak", 0)) + 1
            p["status"] = "review" if p["mastery"] < 5 else "mastered"
            if old_interval < 1:
                interval = 1.0
            else:
                interval = min(90.0, max(1.0, old_interval * 2.15))
            p["interval"] = round(interval, 2)
            p["due_at"] = now + interval * 86400
        else:  # 쉬움
            p["mastery"] = min(5, old_mastery + 2)
            p["streak"] = int(p.get("streak", 0)) + 1
            p["status"] = "mastered" if p["mastery"] >= 4 else "review"
            if old_interval < 1:
                interval = 3.0
            else:
                interval = min(180.0, max(3.0, old_interval * 3.0))
            p["interval"] = round(interval, 2)
            p["due_at"] = now + interval * 86400

        self.save_state()
        self.start_next()

